#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Apply the CCF 2026 recommended-list changes (《中国计算机学会推荐国际学术
会议和期刊目录》2026版) to the extension's generated ccf*.js data files and
regenerate dataGen.js's ccfRankList so the hand-maintained source stays in sync.

Diff source: CCF2026-UTF8.csv from github.com/hitfyd/ShowJCR, cross-checked
against dblp stream keys (several CSV urls are wrong or non-dblp; see MANUAL
notes below). Applied changes:

  rank change:
    /journals/bioinformatics        B -> A
  additions (real dblp streams):
    /conf/fscd        C  FSCD        International Conference on Formal Structures for Computation and Deduction
    /conf/cisc        C  Inscrypt    Conference on Information Security and Cryptology (dblp stream verified)
    /journals/behaviourIT C BIT      Behaviour & Information Technology (dblp key is mixed-case!)
  additions (no dblp stream; pseudo urls for venue-name matching on publisher pages):
    /journals/cognition B Cognition
    /journals/jslhr   B  JSLHR       Journal of Speech Language and Hearing Research
    /journals/jasa    B  JASA        Journal of the Acoustical Society of America
    /journals/iet-its C  IET-ITS     IET Intelligent Transport Systems
    /journals/jats    C  JATS        ACM Journal on Autonomous Transportation Systems
    /conf/hotsec      C  HotSec      (useless for url lookup, kept for completeness)
    /conf/jointcloud  C  JCC         International Conference on JointCloud Computing
  removals (dropped from the 2026 list):
    /conf/icisc  C  (Korean ICISC no longer listed; 2026 lists the Chinese CISC instead)
    /conf/parco  B  (ParCo conference no longer listed; journal entry /journals/pc remains)
"""

import json
import os
import re
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.abspath(os.path.join(HERE, "..", "data"))

# rank: canon url -> rank
rankUrl = load = None


def load_js(fname, var):
    text = open(os.path.join(DATA, fname), encoding="utf-8").read()
    m = re.search(r"ccf\." + var + r"\s*=\s*(\{.*?\});", text, re.S)
    if not m:
        raise ValueError(f"{var} not found in {fname}")
    return json.loads(m.group(1))


rankUrl = load_js("ccfRankUrl.js", "rankUrl")
rankAbbr = load_js("ccfRankAbbr.js", "rankAbbrName")
rankFull = load_js("ccfRankFull.js", "rankFullName")
rankDb = load_js("ccfRankDb.js", "rankDb")
fullUrl = load_js("ccfFullUrl.js", "fullUrl")
abbrFull = load_js("ccfAbbrFull.js", "abbrFull")

COPYRIGHT = """/**
 * MIT License
 *
 * WenyanLiu (https://github.com/WenyanLiu/CCFrank4dblp)
 * Copyright (c) 2019-2026 All Rights Reserved.
 * ------------------------------------------------------
 * Generated by dataGen.js + build/update_ccf_2026.py (CCF 2026 list)
 * Last updated: %s
 */
"""

# ---------------------------------------------------------------- changes --

RANK_CHANGES = {
    "/journals/bioinformatics/bioinformatics": "A",
}

# canon url, stream, rank, abbr, full name
ADDITIONS = [
    ("/conf/fscd/fscd", "/conf/fscd", "C", "FSCD", "International Conference on Formal Structures for Computation and Deduction"),
    ("/conf/cisc/cisc", "/conf/cisc", "C", "Inscrypt", "Conference on Information Security and Cryptology"),
    ("/journals/behaviourIT/behaviourIT", "/journals/behaviourIT", "C", "BIT", "Behaviour & Information Technology"),
    # no dblp stream — pseudo urls, resolved via venue-name matching only
    ("/nondblp/cognition", "/nondblp/cognition", "B", "Cognition", "Cognition"),
    ("/nondblp/jslhr", "/nondblp/jslhr", "B", "JSLHR", "Journal of Speech, Language, and Hearing Research"),
    ("/nondblp/jasa", "/nondblp/jasa", "B", "JASA", "Journal of the Acoustical Society of America"),
    ("/nondblp/iet-its", "/nondblp/iet-its", "C", "IET-ITS", "IET Intelligent Transport Systems"),
    ("/nondblp/jats", "/nondblp/jats", "C", "JATS", "ACM Journal on Autonomous Transportation Systems"),
    ("/nondblp/hotsec", "/nondblp/hotsec", "C", "HotSec", "International Symposium on Hot Topics in Security"),
    ("/nondblp/jointcloud", "/nondblp/jointcloud", "C", "JCC", "International Conference on JointCloud Computing"),
]

REMOVALS = ["/conf/icisc", "/conf/parco"]


def remove_venue(stream):
    canon = rankDb.get(stream)
    if canon is None:
        canon = stream if stream in rankUrl else None
    if canon is None:
        print(f"  ! removal skipped, unknown: {stream}")
        return
    rankUrl.pop(canon, None)
    rankAbbr.pop(canon, None)
    rankFull.pop(canon, None)
    full = None
    for name, u in list(fullUrl.items()):
        if u == canon:
            full = name
            del fullUrl[name]
    if full:
        abbrFull.pop(re.sub(r"\s+", "", full.split("(")[0]).strip().upper(), None)
    for s in [k for k, v in rankDb.items() if v == canon]:
        del rankDb[s]
    print(f"  - removed {canon} ({full})")


def add_venue(canon, stream, rank, abbr, full):
    rankUrl[canon] = rank
    rankFull[canon] = full
    rankAbbr[canon] = abbr
    rankDb[stream] = canon
    fullUrl[full.upper()] = canon
    if abbr:
        abbrFull[abbr] = full.upper()
    print(f"  + added {canon} {rank} {abbr} {full[:45]}")


def main():
    today = date.today().isoformat()
    print("Applying CCF 2026 changes...")

    for canon, rank in RANK_CHANGES.items():
        old = rankUrl.get(canon, "?")
        rankUrl[canon] = rank
        print(f"  ~ rank {canon}: {old} -> {rank}")

    for stream in REMOVALS:
        remove_venue(stream)

    for canon, stream, rank, abbr, full in ADDITIONS:
        if canon in rankUrl:
            print(f"  ! already present, skipped: {canon}")
            continue
        add_venue(canon, stream, rank, abbr, full)

    # ------------------------------------------------ regenerate files -----
    def write(fname, pairs):
        body = "".join(
            f"ccf.{var} = {json.dumps(obj, ensure_ascii=False, sort_keys=True, indent=None, separators=(',', ':'))};\n"
            for var, obj in pairs
        )
        with open(os.path.join(DATA, fname), "w", encoding="utf-8") as f:
            f.write((COPYRIGHT % today) + body)

    write("ccfRankUrl.js", [("rankUrl", rankUrl)])
    write("ccfRankAbbr.js", [("rankAbbrName", rankAbbr)])
    write("ccfRankFull.js", [("rankFullName", rankFull)])
    write("ccfRankDb.js", [("rankDb", rankDb)])
    write("ccfFullUrl.js", [("fullUrl", fullUrl)])
    write("ccfAbbrFull.js", [("abbrFull", abbrFull)])

    # regenerate dataGen.js's ccfRankList TSV (source of truth kept in sync)
    lines = []
    for stream, canon in rankDb.items():
        if canon not in rankUrl:
            continue
        lines.append(
            "\t".join([rankUrl[canon], rankAbbr.get(canon, ""), rankFull.get(canon, ""), stream, canon])
        )
    tsv = " +\n  ".join(json.dumps(l + "\n") for l in lines)
    gen_path = os.path.join(DATA, "dataGen.js")
    gen = open(gen_path, encoding="utf-8").read()
    new_gen = re.sub(
        r"const ccfRankList =\n(?:  \".*\"\s*\+\n)*  \".*\";",
        lambda m: f"const ccfRankList =\n  {tsv};",
        gen,
        count=1,
        flags=re.S,
    )
    if new_gen == gen:
        print("  ! dataGen.js ccfRankList not rewritten (pattern mismatch)")
    else:
        open(gen_path, "w", encoding="utf-8").write(new_gen)
        print(f"  dataGen.js ccfRankList regenerated ({len(lines)} lines)")

    print(f"Done: {len(rankUrl)} ranked venues, {len(rankDb)} stream mappings.")


if __name__ == "__main__":
    main()
